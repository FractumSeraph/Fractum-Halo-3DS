"""port/n3ds/tools/ce_schemas.py: port/n3ds/setup/Resources/schemas.json (the
tag layouts Halo3DS's setup relocates Xbox maps with, Halo PC's too) as C
tables for the 3DS's own relocation of Custom Edition maps
(port/n3ds/src/engine_ce_relocate.c): for each layout its size and the
fields that hold or lead to pointers (blocks, references, data, plain
pointers, nested layouts), and the tag groups' root layouts.

  python port/n3ds/tools/ce_schemas.py > port/n3ds/src/engine_ce_schemas.inl
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SCHEMAS = os.path.join(HERE, '..', 'setup', 'Resources', 'schemas.json')
KINDS = {'TagReflexive': 'CE_FIELD_BLOCK', 'TagDependency': 'CE_FIELD_REFERENCE',
         'TagDataOffset': 'CE_FIELD_DATA', 'Pointer': 'CE_FIELD_POINTER'}


def main():
    schemas = json.load(open(SCHEMAS, encoding='utf-8'))
    types = schemas['Types']
    names = sorted(types)
    index = {name: i for i, name in enumerate(names)}
    fields, rows = [], []
    for name in names:
        layout = types[name]
        first = len(fields)
        for field in layout['Fields']:
            kind = KINDS.get(field['Type'])
            target = -1
            if kind == 'CE_FIELD_BLOCK':
                target = index[field['Struct']]
            elif kind is None and field['Type'] in types:
                kind, target = 'CE_FIELD_STRUCT', index[field['Type']]
            if kind is None:
                continue
            special = 0
            if name == 'Scenario' and field['Name'] == 'script syntax data':
                special = 1
            fields.append((field['Offset'], kind, target, special, name, field['Name']))
        rows.append((layout['Size'], first, len(fields) - first, name))
    out = sys.stdout
    out.write('/* Generated by port/n3ds/tools/ce_schemas.py from port/n3ds/setup/Resources/schemas.json:\n'
              ' * do not edit. %d layouts, %d pointer-bearing fields, %d tag groups. */\n'
              % (len(rows), len(fields), len(schemas['Roots'])))
    out.write('static const struct ce_schema_field ce_schema_fields[] = {\n')
    for offset, kind, target, special, owner, fname in fields:
        out.write('\t{ %d, %s, %d, %d }, /* %s: %s */\n' % (offset, kind, target, special, owner, fname.replace('*/', '* /')))
    out.write('};\n')
    out.write('static const struct ce_schema_type ce_schema_types[] = {\n')
    for size, first, count, name in rows:
        out.write('\t{ %d, %d, %d }, /* %d %s */\n' % (size, first, count, index[name], name))
    out.write('};\n')
    out.write('static const struct ce_schema_root ce_schema_roots[] = {\n')
    for group, name in sorted(schemas['Roots'].items(), key=lambda kv: int(kv[0])):
        if name in index:
            out.write('\t{ 0x%08XU, %d }, /* %s */\n' % (int(group), index[name], name))
    out.write('};\n')
    for special in ('ScenarioStructureBSP', 'ScenarioStructureBSPCompiledHeader'):
        out.write('#define CE_SCHEMA_%s %d\n' % (special.upper(), index[special]))


if __name__ == '__main__':
    main()
